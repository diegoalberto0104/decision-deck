const DICCIONARIOS: Record<string, Record<Clave, string>> = { es, en }

/** Idioma de la interfaz: el de la config; antes de cargarla, el del navegador. */
function lengua(): string {
  let tag: string
  try { tag = idioma() } catch { tag = typeof navigator === 'undefined' ? 'es' : navigator.language }
  const base = tag.split('-')[0].toLowerCase()
  return base in DICCIONARIOS ? base : 'es'
}

export function t(clave: Clave, vars: Record<string, string | number> = {}): string {
  const texto = DICCIONARIOS[lengua()][clave] ?? es[clave]
  return texto.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m))
}
